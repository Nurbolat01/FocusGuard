from PIL import Image, ImageDraw

def create_app_icon():
    size = (512, 512)
    image = Image.new("RGBA", size, (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)

    # Внешний щит (тёмно-синяя грань)
    shield_outer = [
        (256, 40),   # верхний центр
        (430, 90),   # верхний правый
        (410, 320),  # изгиб справа
        (256, 470),  # нижний острый край
        (102, 320),  # изгиб слева
        (82, 90)     # верхний левый
    ]
    draw.polygon(shield_outer, fill=(20, 25, 40, 255))

    # Внутренний щит (основное тело)
    shield_inner = [
        (256, 60),
        (410, 105),
        (392, 310),
        (256, 445),
        (120, 310),
        (102, 105)
    ]
    draw.polygon(shield_inner, fill=(15, 20, 30, 255))

    # Неоновые акцентные линии по контуру щита
    draw.line([(256, 60), (410, 105), (392, 310), (256, 445)], fill=(30, 144, 255, 255), width=6)
    draw.line([(256, 60), (102, 105), (120, 310), (256, 445)], fill=(0, 210, 255, 255), width=6)

    # Синий огонь / Пламя фокуса в центре
    flame_outer = [
        (256, 150),
        (290, 220),
        (330, 250),
        (310, 320),
        (256, 370),
        (202, 320),
        (182, 250),
        (222, 220)
    ]
    draw.polygon(flame_outer, fill=(30, 144, 255, 255))

    flame_inner = [
        (256, 190),
        (278, 240),
        (300, 270),
        (285, 320),
        (256, 350),
        (227, 320),
        (212, 270),
        (234, 240)
    ]
    draw.polygon(flame_inner, fill=(0, 220, 255, 255))

    # Сохранение в PNG и сразу в ICO
    image.save("icon.png", "PNG")
    
    # Сохраняем ICO со всеми стандартными размерами Windows
    icon_sizes = [(16, 16), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)]
    image.save("icon.ico", format="ICO", sizes=icon_sizes)
    print("Иконки успешно созданы: icon.png и icon.ico")

if __name__ == "__main__":
    create_app_icon()